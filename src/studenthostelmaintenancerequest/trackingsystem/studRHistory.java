private void applyFilter() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) jTable1.getModel();
    javax.swing.table.TableRowSorter<javax.swing.table.DefaultTableModel> sorter =
        new javax.swing.table.TableRowSorter<>(model);
    jTable1.setRowSorter(sorter);

    // Build combined filter for Status (col 4) and Type (col 1)
    java.util.List<javax.swing.RowFilter<Object, Object>> filters = new java.util.ArrayList<>();

    if (!filterStatus.equals("All")) {
        filters.add(javax.swing.RowFilter.regexFilter(
            "(?i)^" + filterStatus + "$", 4));
    }
    if (!filterType.equals("All")) {
        filters.add(javax.swing.RowFilter.regexFilter(
            "(?i)^" + filterType + "$", 1));
    }

    if (filters.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(javax.swing.RowFilter.andFilter(filters));
    }
    }//GEN-LAST:event_jButton7ActionPerformed
 

