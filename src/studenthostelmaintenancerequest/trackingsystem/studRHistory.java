    private void applySearchAndFilter() {
        String keyword = jTextField1.getText().trim().toLowerCase();
 
        filteredData = new ArrayList<>();
 
        for (Object[] row : allData) {
            // 1. Keyword: must appear in any column
            boolean keywordMatch = keyword.isEmpty();
            if (!keywordMatch) {
                for (Object cell : row) {
                    if (cell != null && cell.toString().toLowerCase().contains(keyword)) {
                        keywordMatch = true;
                        break;
                    }
                }
            }
            // 2. Status filter (col 4)
            boolean statusMatch = filterStatus.equals("All")
                    || row[4].toString().equalsIgnoreCase(filterStatus);
            // 3. Type filter (col 1)
            boolean typeMatch = filterType.equals("All")
                    || row[1].toString().equalsIgnoreCase(filterType);
 
            if (keywordMatch && statusMatch && typeMatch) {
                filteredData.add(row);
            }
        }
 
        currentPage = 1;   // always restart at page 1 after search/filter
        renderPage();
    }
 
    /** Slices filteredData for the current page and loads it into the table. */
    private void renderPage() {
        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
 
        int total      = filteredData.size();
        int totalPages = Math.max(1, (int) Math.ceil((double) total / rowsPerPage));
 
        // Clamp
        if (currentPage < 1)           currentPage = 1;
        if (currentPage > totalPages)  currentPage = totalPages;
 
        int start = (currentPage - 1) * rowsPerPage;
        int end   = Math.min(start + rowsPerPage, total);
 
        for (int i = start; i < end; i++) {
            model.addRow(filteredData.get(i));
        }
 
        jLabel3.setText(total == 0
            ? "No results found"
            : "Showing " + (start + 1) + " to " + end + " of " + total + " results");
 
        jButton5.setEnabled(currentPage > 1);
        jButton6.setEnabled(currentPage < totalPages);
    }
 
